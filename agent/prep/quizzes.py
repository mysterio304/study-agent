"""Quiz engine (SPEC §6 Enforcement, §7, §9a.6).

- Questions are generated by Haiku from the topic's best course-file excerpts (FTS), schema-
  constrained and fitted to Telegram quiz-poll limits, then kept in a per-topic bank and reused.
- Tomorrow's topics are generated overnight in ONE Message Batch (50 % cheaper); if a block ends and
  the bank is short, a single on-demand call fills it.
- Verification (block end): ≥ 2/3 correct → passed → full study credit and possible level-up;
  failed → only half the minutes count as progress and the topic is reviewed tomorrow;
  unanswered for 3 h → counted as done but not verified.
"""

from __future__ import annotations

import asyncio
import json
import logging
from dataclasses import dataclass
from datetime import timedelta
from typing import Any

from sqlalchemy import func, select
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from agent.brain.batches import BatchItem, BatchRunner, Purpose
from agent.brain.llm import BudgetExceeded, LlmClient, text_of
from agent.core.clock import Clock
from agent.db.models import Block, Exam, LlmBatch, Quiz, QuizQuestion, StudySession, Topic
from agent.files.search import FtsRetriever
from agent.planner.blocks import set_block_status

log = logging.getLogger(__name__)

PURPOSE = "quiz_generate"
QUESTIONS_PER_BLOCK = 3
PASS_RATIO = 2 / 3
QUIZ_EXPIRY = timedelta(hours=3)
CONTEXT_CHUNKS = 4
LEVEL2_PASSES = 2
MAX_ON_DEMAND_TOPICS = 15

# Telegram quiz-poll limits (Bot API): question ≤ 300, option ≤ 100, explanation ≤ 200 chars.
Q_MAX, OPT_MAX, EXPL_MAX = 300, 100, 200

QUIZ_SYSTEM = (
    "You write multiple-choice questions that test real understanding (not trivia) of ONE topic of a "
    "university final exam, using ONLY the provided course excerpts. Questions and options in English "
    "(the exam language); the explanation in Russian, one sentence. Exactly 4 options, one correct, "
    "plausible distractors. question ≤ 250 chars, each option ≤ 90 chars, explanation ≤ 180 chars. "
    "source = the excerpt label you used, e.g. 'Lecture 5.pdf, p. 12'."
)

QUIZ_SCHEMA: dict[str, Any] = {
    "type": "object",
    "properties": {
        "questions": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "question": {"type": "string"},
                    "options": {"type": "array", "items": {"type": "string"}},
                    "correct": {"type": "integer"},
                    "explanation": {"type": "string"},
                    "source": {"type": "string"},
                },
                "required": ["question", "options", "correct", "explanation", "source"],
                "additionalProperties": False,
            },
        }
    },
    "required": ["questions"],
    "additionalProperties": False,
}


def _fit(text: str, limit: int) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def parse_questions(raw: str) -> list[dict[str, Any]]:
    """Validate model output and fit it to Telegram limits; malformed questions are dropped."""
    out = []
    for q in json.loads(raw).get("questions", []):
        options = [_fit(o, OPT_MAX) for o in q.get("options", []) if str(o).strip()]
        correct = q.get("correct")
        if (
            not 2 <= len(options) <= 6
            or not isinstance(correct, int)
            or not 0 <= correct < len(options)
        ):
            continue
        if len(set(options)) != len(options) or not str(q.get("question", "")).strip():
            continue
        out.append(
            {
                "question": _fit(q["question"], Q_MAX),
                "options": options,
                "correct": correct,
                "explanation": _fit(q.get("explanation", ""), EXPL_MAX),
                "source": _fit(q.get("source", ""), 80),
            }
        )
    return out


async def topic_context(session: AsyncSession, topic: Topic) -> str | None:
    exam = await session.get(Exam, topic.exam_id)
    if exam is None or exam.course_id is None:
        return None
    hits = await FtsRetriever().search(
        session,
        f"{topic.name} {topic.description or ''}",
        course_id=exam.course_id,
        limit=CONTEXT_CHUNKS,
    )
    if not hits:
        return None
    return "\n\n".join(f"[{h.citation()}]\n{h.text}" for h in hits)


def quiz_prompt(topic: Topic, context: str, n: int) -> str:
    return f"Topic: {topic.name}\nWrite {n} questions.\n\nExcerpts:\n{context}"


async def store_questions(
    session: AsyncSession, topic_id: int, questions: list[dict[str, Any]], origin: str, clock: Clock
) -> int:
    for q in questions:
        session.add(
            QuizQuestion(
                topic_id=topic_id,
                question_json=q,
                origin=origin,
                times_used=0,
                retired=False,
                created_at=clock.now(),
            )
        )
    await session.flush()
    return len(questions)


async def unused_count(session: AsyncSession, topic_id: int) -> int:
    return int(
        await session.scalar(
            select(func.count())
            .select_from(QuizQuestion)
            .where(
                QuizQuestion.topic_id == topic_id,
                QuizQuestion.retired.is_(False),
                QuizQuestion.times_used == 0,
            )
        )
        or 0
    )


async def generate_on_demand(
    sm: async_sessionmaker,
    llm: LlmClient,
    topic_id: int,
    clock: Clock,
    n: int = QUESTIONS_PER_BLOCK,
) -> int:
    """One Haiku call (no DB transaction held across it). Returns questions stored."""
    async with sm() as s:
        topic = await s.get(Topic, topic_id)
        context = await topic_context(s, topic) if topic else None
    if context is None:
        return 0
    try:
        res = await llm.call(
            PURPOSE,
            system=QUIZ_SYSTEM,
            messages=[{"role": "user", "content": quiz_prompt(topic, context, n)}],
            json_schema=QUIZ_SCHEMA,
        )
        questions = parse_questions(text_of(res.message))
    except (BudgetExceeded, ValueError) as exc:
        log.info("Quiz generation skipped for topic %s: %s", topic_id, type(exc).__name__)
        return 0
    async with sm() as s:
        stored = await store_questions(s, topic_id, questions, "on_demand", clock)
        await s.commit()
    return stored


async def pick_questions(
    session: AsyncSession, topic_id: int, n: int, clock: Clock
) -> list[dict[str, Any]]:
    """Least-used questions first; marks them used."""
    rows = list(
        (
            await session.scalars(
                select(QuizQuestion)
                .where(QuizQuestion.topic_id == topic_id, QuizQuestion.retired.is_(False))
                .order_by(QuizQuestion.times_used, QuizQuestion.id)
                .limit(n)
            )
        ).all()
    )
    for r in rows:
        r.times_used += 1
        r.last_used_at = clock.now()
    await session.flush()
    return [{**r.question_json, "qid": r.id, "poll_id": None, "answer": None} for r in rows]


# --- nightly batch -----------------------------------------------------------------------------


class QuizBank:
    """Fills question banks: nightly batch for tomorrow's topics, on-demand fallback."""

    def __init__(
        self, sm: async_sessionmaker, llm: LlmClient, batches: BatchRunner | None, clock: Clock
    ) -> None:
        self._sm, self._llm, self._batches, self._clock = sm, llm, batches, clock
        if batches is not None:
            batches.register(
                PURPOSE, Purpose(self._on_results, self._on_timeout, deadline=timedelta(hours=3))
            )
        self.on_ready: list[Any] = []  # callbacks(meta) run after a batch is stored (diagnostic)

    async def topics_needing_questions(
        self, topic_ids: list[int], per_topic: int
    ) -> dict[int, str]:
        prompts: dict[int, str] = {}
        async with self._sm() as s:
            in_flight = {  # topics already in a pending batch: never submit them twice
                tid
                for b in (
                    await s.scalars(
                        select(LlmBatch).where(
                            LlmBatch.purpose == PURPOSE, LlmBatch.status == "submitted"
                        )
                    )
                ).all()
                for tid in (b.meta_json or {}).get("topic_ids", [])
            }
            for tid in dict.fromkeys(topic_ids):
                if tid in in_flight or await unused_count(s, tid) >= per_topic:
                    continue
                topic = await s.get(Topic, tid)
                context = await topic_context(s, topic) if topic else None
                if context:
                    prompts[tid] = quiz_prompt(topic, context, per_topic + 1)
        return prompts

    async def fill(
        self,
        topic_ids: list[int],
        *,
        per_topic: int = QUESTIONS_PER_BLOCK,
        meta: dict[str, Any] | None = None,
    ) -> str:
        """Returns 'ready' (nothing to do), 'batched' or 'generated' (on demand, no batch runner)."""
        prompts = await self.topics_needing_questions(topic_ids, per_topic)
        if not prompts:
            return "ready"
        if self._batches is None:
            for tid in list(prompts)[:MAX_ON_DEMAND_TOPICS]:  # bounded: runs inside a chat handler
                await generate_on_demand(self._sm, self._llm, tid, self._clock, per_topic + 1)
            return "generated"
        items = [
            BatchItem(
                f"topic-{tid}", PURPOSE, QUIZ_SYSTEM, [{"role": "user", "content": p}], QUIZ_SCHEMA
            )
            for tid, p in prompts.items()
        ]
        await self._batches.submit(PURPOSE, items, {"topic_ids": list(prompts), **(meta or {})})
        return "batched"

    async def nightly(self) -> str:
        """Tomorrow's planned topics → one batch."""
        start = self._clock.now() + timedelta(hours=1)
        async with self._sm() as s:
            ids = list(
                (
                    await s.scalars(
                        select(Block.topic_id).where(
                            Block.status == "planned",
                            Block.topic_id.is_not(None),
                            Block.starts_at >= start,
                            Block.starts_at < start + timedelta(days=1),
                        )
                    )
                ).all()
            )
        return await self.fill([i for i in ids if i is not None])

    async def _on_results(self, row: LlmBatch, results: dict[str, Any | None]) -> None:
        async with self._sm() as s:
            for custom_id, msg in results.items():
                if msg is None:
                    continue
                try:
                    questions = parse_questions(text_of(msg))
                except ValueError:
                    continue
                await store_questions(
                    s, int(custom_id.removeprefix("topic-")), questions, "batch", self._clock
                )
            await s.commit()
        for callback in self.on_ready:
            await callback(row.meta_json or {})

    async def _on_timeout(self, row: LlmBatch) -> None:
        for tid in (row.meta_json or {}).get("topic_ids", []):
            await generate_on_demand(self._sm, self._llm, tid, self._clock, QUESTIONS_PER_BLOCK + 1)
        for callback in self.on_ready:
            await callback(row.meta_json or {})


# --- verification -----------------------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class QuizOutcome:
    quiz_id: int
    correct: int
    total: int
    passed: bool | None  # None = expired unanswered
    level_change: tuple[int, int] | None = None
    purpose: str = "verification"


async def start_quiz(
    session: AsyncSession,
    topic_id: int,
    clock: Clock,
    *,
    purpose: str,
    block_id: int | None,
    n: int,
) -> Quiz | None:
    available = await session.scalar(
        select(func.count())
        .select_from(QuizQuestion)
        .where(QuizQuestion.topic_id == topic_id, QuizQuestion.retired.is_(False))
    )
    if (available or 0) < min(2, n):  # check first: don't mark questions used for a quiz never sent
        return None
    questions = await pick_questions(session, topic_id, n, clock)
    quiz = Quiz(
        topic_id=topic_id,
        block_id=block_id,
        purpose=purpose,
        questions_json=questions,
        answers_json=[],
        created_at=clock.now(),
    )
    session.add(quiz)
    await session.flush()
    return quiz


def _score(quiz: Quiz) -> tuple[int, int]:
    answered = [q for q in quiz.questions_json if q.get("answer") is not None]
    return sum(q["answer"] == q["correct"] for q in answered), len(quiz.questions_json)


# Poll answers arrive as concurrent aiogram tasks; each rewrites the quiz's JSON, so they must be
# serialised or the last writer silently drops the other answer (single process → one lock).
ANSWER_LOCK = asyncio.Lock()


async def record_answer(
    session: AsyncSession, poll_id: str, option: int, clock: Clock
) -> QuizOutcome | None:
    """Store one poll answer; when the quiz is complete, finalize it. Returns the outcome when final."""
    quizzes = (await session.scalars(select(Quiz).where(Quiz.finished_at.is_(None)))).all()
    for quiz in quizzes:
        questions = list(quiz.questions_json)
        for i, q in enumerate(questions):
            if q.get("poll_id") == poll_id and q.get("answer") is None:
                questions[i] = {**q, "answer": option}
                quiz.questions_json = questions  # reassign: JSON column change tracking
                await session.flush()
                if all(x.get("answer") is not None for x in questions):
                    return await finalize(session, quiz, clock)
                return None
    return None


async def finalize(
    session: AsyncSession, quiz: Quiz, clock: Clock, *, expired: bool = False
) -> QuizOutcome:
    correct, total = _score(quiz)
    passed = None if expired else correct >= PASS_RATIO * total - 1e-9
    quiz.score = correct / total if total else 0
    quiz.passed = passed
    quiz.finished_at = clock.now()
    change = None
    if quiz.purpose == "verification" and quiz.block_id is not None:
        change = await _apply_verification(session, quiz, passed, clock)
    await session.flush()
    return QuizOutcome(quiz.id, correct, total, passed, change, quiz.purpose)


async def _apply_verification(
    session: AsyncSession, quiz: Quiz, passed: bool | None, clock: Clock
) -> tuple[int, int] | None:
    block = await session.get(Block, quiz.block_id)
    topic = await session.get(Topic, quiz.topic_id)
    if block is None or topic is None:
        return None
    await set_block_status(session, block.id, "done", clock)
    minutes = int((block.ends_at - block.starts_at).total_seconds() // 60)
    study = await session.scalar(
        select(StudySession)
        .where(StudySession.block_id == block.id)
        .order_by(StudySession.id.desc())
    )
    if study is not None:
        study.verified, study.quiz_score = passed is True, quiz.score
    if passed is False:  # only half the block counts towards progress; review tomorrow
        if block.kind in ("learn", "practice"):
            topic.progress_min = max(0, (topic.progress_min or 0) - minutes // 2)
        topic.next_review_at = clock.now() + timedelta(days=1)
        return None
    if passed is None:
        return None
    return await _maybe_level_up(session, topic, block.kind, clock)


async def _maybe_level_up(
    session: AsyncSession, topic: Topic, kind: str, clock: Clock
) -> tuple[int, int] | None:
    old = topic.level
    if topic.level == 0:  # any passed block on an untouched topic: 0 → 1 first, never straight to 2
        new = 1
    else:
        since = topic.level_changed_at
        q = (
            select(func.count())
            .select_from(Quiz)
            .where(Quiz.topic_id == topic.id, Quiz.purpose == "verification", Quiz.passed.is_(True))
        )
        if since is not None:
            q = q.where(Quiz.created_at > since)  # only quizzes after the last level change
        passes = int(await session.scalar(q) or 0)
        if not (passes >= LEVEL2_PASSES and topic.level < 2):
            return None
        new = 2
    topic.level, topic.progress_min, topic.level_changed_at = new, 0, clock.now()
    return old, new


async def expire_stale(session: AsyncSession, clock: Clock) -> list[QuizOutcome]:
    cutoff = clock.now() - QUIZ_EXPIRY
    stale = (
        await session.scalars(
            select(Quiz).where(Quiz.finished_at.is_(None), Quiz.created_at < cutoff)
        )
    ).all()
    return [await finalize(session, q, clock, expired=True) for q in stale]
